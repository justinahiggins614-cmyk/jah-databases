// Build Database tool — UI + logic for db/database-builder/index.html
// (Injected as a new tab. Uses build-tool-core.js templates via <script> include.)
(function(){
'use strict';
if(!document.getElementById('p-build')) return; // tab not present

var $=function(id){return document.getElementById(id);};
function esc(s){return String(s==null?'':s).replace(/[&<>"]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c];});}

var TYPE_OPTS=[
  ['general','General purpose — a full database on ANY subject'],
  ['user-idea','User-idea database — your idea, fully worked out'],
  ['ecosystem','Ecosystem database — builds everything one at a time'],
  ['reverse-allowance','Reverse universal allowance database — solve by working backwards'],
  ['book','Book database — the full book in every file']
];
// Populated from core TYPE_LABELS if available
function typeOptions(){
  if(typeof DBTOOL_CORE!=='undefined'&&DBTOOL_CORE.TYPE_LABELS){
    return Object.keys(DBTOOL_CORE.TYPE_LABELS).map(function(k){return [k,DBTOOL_CORE.TYPE_LABELS[k]];});
  }
  return TYPE_OPTS;
}

function buildPageSource(cfg){
  // Clone THIS page as the template (guarantees all fixes carry over).
  var clone=document.documentElement.cloneNode(true);
  // Remove the builder tab, pane, and tool scripts from the clone.
  var btab=clone.querySelector('[data-p="build"]'); if(btab) btab.remove();
  var bpane=clone.querySelector('#p-build'); if(bpane) bpane.remove();
  var bscript=clone.querySelector('#buildToolScript'); if(bscript) bscript.remove();
  var coreScript=clone.querySelector('script[src*="build-tool-core"]'); if(coreScript) coreScript.remove();
  var jszip=clone.querySelector('script[src*="jszip"]'); if(jszip) jszip.remove();
  // Replace generator script tag
  var genTag=clone.querySelector('script[src*="gen-database-builder"]');
  if(genTag) genTag.setAttribute('src','gen-'+cfg.slug+'.js');
  var html='<!DOCTYPE html>\n'+clone.outerHTML;
  // Parameterize
  var reps=[
    [/database-builder/g, cfg.slug],
    [/Database Builder Database/g, cfg.name],
    [/JAH Database Architect/g, cfg.aiName],
    [/database construction pattern/g, cfg.recordKind],
    [/JAH-DBBUILD-/g, cfg.prefix],
    [/jahdb-database-builder-1\.0/g, 'jahdb-'+cfg.slug+'-1.0'],
    [/The database for building databases: schemas, structures, templates, record designs, generator patterns, and the complete standards for constructing a proper database to JAH standards\./g, esc(cfg.topic)],
  ];
  reps.forEach(function(rp){ html=html.replace(rp[0],rp[1]); });
  return html;
}

function seedRecords(cfg, n){
  // Eval the generated generator, then seed n records.
  var src=DBTOOL_CORE.buildGenerator(cfg);
  var mod={exports:{}};
  new Function('module','JAHDB',src)(mod, undefined);
  var g=mod.exports, recs=[];
  for(var i=1;i<=n;i++){
    var r=g.generate(i);
    if(!g.validate(r).ok) throw new Error('seed '+i+' failed validation');
    recs.push(r);
  }
  return {records:recs, genSrc:src};
}

function downloadBlob(blob, name){
  var a=document.createElement('a'); a.href=URL.createObjectURL(blob); a.download=name;
  document.body.appendChild(a); a.click();
  setTimeout(function(){URL.revokeObjectURL(a.href);a.remove();},800);
}

function readmeText(cfg){
  return cfg.name.toUpperCase()+"\nGenerated by the Database Builder Database.\nProperty of Justin Addam Higgins (JAH).\n\nINSTALL:\n1. Unzip. Place db/"+cfg.slug+"/ and data/"+cfg.slug+"/ into the jah-databases repo.\n2. Compress the data files: gzip -k data/"+cfg.slug+"/index.jsonl data/"+cfg.slug+"/chunks/*.jsonl\n   (The page loads .jsonl.gz; keep the .jsonl too or delete after.)\n3. Paste manifest-entry.json into data/manifest.json (databases array).\n4. Paste api-entry.json into api.json.\n5. Commit, push main + gh-pages.\n\nSTANDARDS: full files never stubs \u00b7 own AI via JAHDB.aiAnswer \u00b7 seed-count rule \u00b7 Type "+(cfg.src==='signature'?'2 (Signature-original)':'1 (public info)')+" \u00b7 no website references.\n";
}

$('bbGo').addEventListener('click',function(){
  var out=$('bbOut'); out.innerHTML='<p class="dim">Building database files\u2026</p>';
  try{
    var name=$('bbName').value.trim();
    if(!name){ out.innerHTML='<p class="bad">Enter a database name.</p>'; return; }
    var slug=(typeof DBTOOL_CORE!=='undefined'?DBTOOL_CORE.slugify(name):name.toLowerCase().replace(/[^a-z0-9]+/g,'-'));
    var cfg={
      slug:slug,
      name:/database$/i.test(name)?name:name+' Database',
      topic:$('bbTopic').value.trim()||name,
      recordKind:$('bbKind').value.trim()||'record',
      aiName:$('bbAI').value.trim()||('JAH '+name.split(' ')[0]+' Specialist'),
      prefix:(typeof DBTOOL_CORE!=='undefined'?DBTOOL_CORE.prefixFor(slug):'JAH-DB-'),
      src:$('bbSrc').value, srcLabel:$('bbSrc').value==='signature'?'Signature-authored original':'Public fact-checked information',
      dbType:$('bbType').value
    };
    cfg.name=/database$/i.test(cfg.name)?cfg.name:cfg.name+' Database';
    var n=Math.min(200,Math.max(10,+$('bbN').value||50));

    // 1. generator source
    var genSrc=DBTOOL_CORE.buildGenerator(cfg);
    // 2. seed records (via eval of our own generated code)
    var seeded=seedRecords(cfg,n);
    var recs=seeded.records;
    // 3. index rows + chunk
    var idxRows=recs.map(function(r,i){return JSON.stringify({id:r.id,t:r.title,c:1,g:r.genre});});
    var chunkText=recs.map(function(r){return JSON.stringify(r);}).join('\n');
    // 4. page
    var pageSrc=buildPageSource(cfg);
    // 5. manifest entries
    var manifestEntry=DBTOOL_CORE.buildManifestEntry(cfg,n);
    var files=[
      {path:'db/'+slug+'/index.html', text:pageSrc},
      {path:'db/'+slug+'/gen-'+slug+'.js', text:genSrc},
      {path:'data/'+slug+'/index.jsonl', text:idxRows.join('\n')},
      {path:'data/'+slug+'/chunks/chunk-0001.jsonl', text:chunkText},
      {path:'manifest-entry.json', text:JSON.stringify(manifestEntry,null,2)},
      {path:'README.txt', text:readmeText(cfg)}
    ];
    var totalBytes=files.reduce(function(a,f){return a+f.text.length;},0);
    window._bbFiles=files; window._bbSlug=slug;

    var h='<p class="ok"><b>'+esc(cfg.name)+'</b> built \u2014 '+files.length+' files, '+(totalBytes/1024).toFixed(0)+'KB, '+n+' seeded records.</p>';
    h+='<ul>'+files.map(function(f){return '<li class="mono">'+esc(f.path)+' ('+(f.text.length/1024).toFixed(1)+'KB)</li>';}).join('')+'</ul>';
    h+='<div class="row"><button class="go" id="bbZip">\u2b07 Download ZIP</button> <span class="dim" id="bbZipNote"></span></div>';
    h+='<p class="dim">The ZIP contains the complete file set. Unzip into the jah-databases repo, gzip the .jsonl files, paste the manifest entry, push.</p>';
    out.innerHTML=h;
    $('bbZip').addEventListener('click',downloadZip);
  }catch(e){
    out.innerHTML='<p class="bad">Build failed: '+esc(e.message)+'</p>';
  }
});

function downloadZip(){
  var files=window._bbFiles, slug=window._bbSlug;
  var note=$('bbZipNote');
  if(typeof JSZip==='undefined'){
    // Fallback: download files individually
    note.textContent='JSZip unavailable \u2014 downloading files individually.';
    files.forEach(function(f){
      downloadBlob(new Blob([f.text],{type:'text/plain'}), f.path.replace(/\//g,'_'));
    });
    return;
  }
  note.textContent='Zipping\u2026';
  var zip=new JSZip();
  files.forEach(function(f){ zip.file(f.path, f.text); });
  zip.generateAsync({type:'blob'}).then(function(blob){
    downloadBlob(blob, 'database-'+slug+'.zip');
    note.textContent='Done.';
  }).catch(function(e){ note.textContent='Zip failed: '+e.message; });
}
})();
