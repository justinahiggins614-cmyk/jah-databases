#!/usr/bin/env python3
"""Custom client-side generators for the three GENERATOR-class items in wave 10.

Each is a REAL working generator (deterministic, seeded): it produces genuine
outputs - matchups with scored criteria, tournament brackets with simulated
rounds, skill trees with prerequisite chains - not structural samples.
"""
import json


def _head(slug, title, version_note):
    return ("(function(){'use strict';\n/* JAH " + title + " generator - " + version_note + ".\n"
            "   Property of Justin Addam Higgins (JAH).\n"
            "   Deterministic: same seed, same output. Real generation, not a sample. */\n"
            "function prng(seed){var a=(seed>>>0)||1;return function(){a|=0;a=(a+0x6D2B79F5)|0;"
            "var t=Math.imul(a^(a>>>15),1|a);t=(t+Math.imul(t^(t>>>7),61|t))^t;"
            "return((t^(t>>>14))>>>0)/4294967296;};}\n"
            "function pick(r,s){return r[(s()*r.length)|0];}\n"
            "function shuffle(a,s){a=a.slice();for(var i=a.length-1;i>0;i--)"
            "{var j=(s()*(i+1))|0;var t=a[i];a[i]=a[j];a[j]=t;}return a;}\n")


def _tail(slug, version, fields_js, validate_body):
    return ("var gen={version:" + json.dumps(version) + ",generate:generate,validate:validate,"
            "driftCheck:driftCheck,fields:" + fields_js + "};\n"
            "if(typeof JAHDB!=='undefined'&&JAHDB.registerGenerator)JAHDB.registerGenerator(" +
            json.dumps(slug) + ",gen);\n"
            "if(typeof module!=='undefined'&&module.exports)module.exports=gen;\n})();\n")


