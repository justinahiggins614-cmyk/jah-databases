           "  if(!defn)defn=pick(SKILLS,rnd);\n"
           "  var nodes=buildTree(defn,rnd);\n"
           "  var total=0;for(i=0;i<nodes.length;i++)total+=nodes[i].xp;\n"
           "  var topic='Skill tree: '+defn.s;\n"
