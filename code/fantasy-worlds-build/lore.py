def _mk_specs(cfg):
    rnd = random.Random(int(hashlib.sha256(cfg["slug"].encode()).hexdigest()[:16], 16))
    specs = []
    tiers = ["foundations"] * 11 + ["compounded"] * 11 + ["advanced"] * 12
    for i, core in enumerate(cfg["titles"]):
        attrs = {}
        for a in cfg["attrs"]:
            if a.get("float"):
                attrs[a["key"]] = round(rnd.uniform(a["lo"], a["hi"]), 1)
            else:
                attrs[a["key"]] = rnd.randint(a["lo"], a["hi"])
        c1 = cfg["cats"][0][rnd.randrange(len(cfg["cats"][0]))]
        c2 = cfg["cats"][1][rnd.randrange(len(cfg["cats"][1]))]
        specs.append({"core": core, "g": cfg["fields"][0 if i < 11 else 1 if i < 22 else 2],
                      "tier": tiers[i], "rank": i + 1, "attrs": attrs, "cats": (c1, c2)})
    cfg["specs"] = specs
    return cfg


def S(slug, cls, item_name, record_kind, ai_short, noun, plural, canon,
      prefix, prefix_sig, tagline, role, fields, attrs, cats, titles,
      lex_over=None, polish=None, gen=True):
    lex = dict(DEFAULT_LEX)
    if lex_over:
        lex.update(lex_over)
    cfg = {"slug": slug, "class": cls, "item_name": item_name,
           "record_kind": record_kind, "ai_short": ai_short,
           "noun": noun, "plural": plural, "canon": canon,
           "prefix": prefix, "prefix_sig": prefix_sig,
           "tagline": tagline, "role": role, "fields": fields,
           "attrs": attrs, "cats": cats, "titles": titles,
           "lex": lex, "people": PEOPLE, "places": PLACES,
           "adjs": ADJS, "materials": MATERIALS,
           "polish": bool(polish), "polish_paras": polish or [],
           "gen_version": "jahdb-" + slug + "-1.0"}
    return _mk_specs(cfg)


def A(key, label, unit, lo, hi, float=False):
    d = {"key": key, "label": label, "unit": unit, "lo": lo, "hi": hi}
    if float:
        d["float"] = True
    return d


