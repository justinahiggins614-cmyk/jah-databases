def _wa(tier, start, chain, links):
    # chain: list of words; links: list of explanations aligned between words
    txt = " -> ".join(chain)
    exp = "\n".join("  %s -> %s: %s" % (chain[i], chain[i + 1], links[i]) for i in range(len(chain) - 1))
    return T(
        tier, "Chain from '%s'" % start,
        desc_pub="WORD ASSOCIATION CHAIN:\n\n%s\n\nWHY EACH LINK HOLDS:\n%s"
        % (txt, exp),
        desc_sig="Signature link-sight: from '%s' the mind leaps - %s - a Signature spark-trail. The Signature edition treats every chain as thought showing its footprints." % (start, txt[:60]),
        how_pub="Play it: say the first word that comes to mind, then explain the link - the explanation is the game.",
        how_sig="The Signature way: force the weird link - the surprising chain teaches more.",
        keys=["Start: '%s'." % start,
              "Chain: %s." % txt,
              "Links: %d, each explained." % len(links)],
        demo=("check", {"code": ["CHAIN = %r" % chain, "LINKS = %r" % links],
                        "checks": [("unbroken", "len(LINKS) == len(CHAIN) - 1"),
                                   ("explained", "all(len(l) > 8 for l in LINKS)"),
                                   ("starts_right", "CHAIN[0] == %r" % start)]}),
    )


