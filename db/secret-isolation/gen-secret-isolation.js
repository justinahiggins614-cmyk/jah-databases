'use strict';
/* Boundless generator for secret-isolation — seeded deterministic LCG, hard cap 1e15, throttled. Generated records are labeled generated/simulated, never authentic public record. */
var HARD_CAP = 1e15;
var TOPICS = ["overview", "core rules", "architecture", "worked example", "failure modes", "measurement", "review checklist", "deployment phases", "audit trail", "operator guide", "edge cases", "compatibility", "cost model", "security review", "future work", "worked sample", "decision log"];
var seed = 42;
function nextRand(){ seed = (seed * 1103515245 + 12345) % 2147483648; return seed / 2147483648; }
function pick(arr){ return arr[Math.floor(nextRand() * arr.length)]; }
function parseN(){
  var args = process.argv.slice(2);
  for (var i = 0; i < args.length; i++){
    if (args[i] === '--n' && args[i+1]){ var n = parseInt(args[i+1], 10); if (!isNaN(n) && n > 0) return Math.min(n, 100000); }
  }
  return 5;
}
var n = parseN();
if (n > HARD_CAP) n = HARD_CAP;
var seen = {};
var out = [];
for (var k = 0; k < n; k++){
  var topic = pick(TOPICS);
  var id = 'JAH-G29-SEI-' + String(900001 + k).padStart(6, '0');
  if (seen[id]) continue;
  seen[id] = true;
  out.push({id: id, title: 'Secret Isolation — generated: ' + topic, edition: 'public', src: 'generated', generated: true, ladder_rank: 'compounded', record_kind: 'capability record', full_records: true, body: '<p>Generated (simulated) record for Secret Isolation on the topic ' + topic + '. This generated record illustrates the capability design; it is labeled generated and is not an authentic public record.</p>', feasibility_tier: 'established', implementation_status: 'designed', provenance: 'generated by gen-secret-isolation.js, seeded deterministic', last_verified: '2026-10-25', license: 'CC0'});
}
