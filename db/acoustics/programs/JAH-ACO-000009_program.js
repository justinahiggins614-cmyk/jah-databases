(function(){
var FIELDS={"id":"JAH-ACO-000009","title":"Hearing Safety — 2–4 kHz danger zone","description":"High-frequency sound of 2,000–4,000 Hz is the most damaging to hearing. This is a published hearing-safety reference value, not an estimate. Recommended protection: earplugs.","category":"hearing-safety","src":"online","spec":{"(object keys)":["guideline","detail","protection","application"]}};
var keys=Object.keys(FIELDS);
function show(i){var k=keys[i];if(k===undefined){console.log("no field "+i);return;}console.log("["+i+"] "+k+" ("+(typeof FIELDS[k])+"):");console.log("    "+JSON.stringify(FIELDS[k]).slice(0,300));}
function find(word){word=String(word).toLowerCase();var hits=keys.filter(function(k){return (k+" "+JSON.stringify(FIELDS[k])).toLowerCase().indexOf(word)>=0;});console.log("fields matching \""+word+"\": "+(hits.join(", ")||"(none)"));return hits;}
console.log("=== Hearing Safety — 2–4 kHz danger zone ===");
console.log("Record JAH-ACO-000009 · "+keys.length+" fields:");
keys.forEach(function(k,i){console.log("  ["+i+"] "+k);});
console.log("--- field tour ---");
keys.forEach(function(k,i){show(i);});
try{globalThis.jahDemoAPI={show:show,find:find};}catch(e){}
console.log("Try: jahDemoAPI.show(0) · jahDemoAPI.find(\"word\")");
})();
