// gen-specialist-ai-capability-directory-signature.js -- boundless generator for the specialist-ai-capability-directory-signature database.
// Usage: node gen-specialist-ai-capability-directory-signature.js --n 5
// Deterministic: a seeded LCG drives per-topic parameter variations of the 16
// seed records. Self-regulating: throttled, duplicate-checked,
// hard-stops at 10^15 records or when the variation space is genuinely exhausted.
// Generated records carry "generated": true and src "generated" -- never mixed
// with assistant-built records.
"use strict";
const HARD_CAP = 1e15;
const TOPICS = ["Expertise Profile Schema", "Tool Access Registry", "Capability Limits Register", "Agent Skill Matrix", "Routing Decision Table", "Access Scope Record", "Performance History Card", "Availability Calendar Entry", "Language Coverage Map", "Domain Depth Rating", "Handoff Compatibility Note", "Version and Model Card", "Cost and Latency Profile", "Safety Scope Statement", "Evaluation Snapshot", "Directory Update Procedure"];
function parseN(argv) {
  const i = argv.indexOf("--n");
  if (i >= 0 && argv[i + 1]) {
    const n = parseInt(argv[i + 1], 10);
    if (!isNaN(n) && n >= 0) return Math.min(n, 100000);
  }
  return 5;
}
let seed = 20261025;
function rnd() {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}
const seen = new Set();
function makeRecord(k) {
  const topic = TOPICS[Math.floor(rnd() * TOPICS.length)];
  const variant = 1 + Math.floor(rnd() * 50);
  const key = topic + "#v" + variant;
  if (seen.has(key)) return null;
  seen.add(key);
  return {
    id: "JAH-GEN-" + String(k + 1).padStart(6, "0"),
    slug: "specialist-ai-capability-directory-signature",
    title: "Generated " + topic + " parameter variation v" + variant,
    edition: "public",
    src: "generated",
    generated: true,
    built_by: "generator",
    record_kind: "specialist ai capability record",
    feasibility_tier: "established",
    note: "Deterministic parameter variation (" + key + ") over the 16 seed " +
          "specialist-ai-capability-directory-signature records. Labeled generated; not an assistant-built record."
  };
}
function main() {
  const n = parseN(process.argv.slice(2));
  if (n >= HARD_CAP) { console.error("hard cap reached"); process.exit(1); }
  const space = TOPICS.length * 50;
  let emitted = 0, attempts = 0;
  while (emitted < n && attempts < n * 20 && seen.size < space) {
    attempts++;
    const rec = makeRecord(emitted);
    if (rec) { console.log(JSON.stringify(rec)); emitted++; }
  }
  console.error("emitted " + emitted + " generated records for specialist-ai-capability-directory-signature");
}
main();
