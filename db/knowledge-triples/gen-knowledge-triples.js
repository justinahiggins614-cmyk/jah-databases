function generate(seed,opts,rnd){
  rnd=rnd||prng(seed);
  var cat=opts.category||pick(rnd,CATS);
  var bank=F[cat]||F.general;
  var f=bank[ri(rnd,0,bank.length-1)];
  var conf=0.7+rnd()*0.3; conf=Math.round(conf*100)/100;
  var title=(f[0]+' '+f[1]+' '+f[2]).slice(0,160);
  return {
    id:'JAH-KG-'+String(seed).padStart(6,'0'),
    triple_id:'JAH-KG-'+String(seed).padStart(6,'0'),
    subject:f[0], predicate:f[1], object:f[2],
    confidence:conf, source:f[3], domain:cat,
    title:title
  };
}
function validate(r){
  var e=[];
  if(!r||typeof r!=='object')return{ok:false,errors:['not an object']};
  ['id','triple_id','subject','predicate','object','confidence','source','domain','title'].forEach(function(k){if(r[k]===undefined||r[k]==='')e.push('missing '+k);});
  if(r.id&&!/^JAH-KG-\d{6}$/.test(r.id))e.push('bad id');
  if(r.triple_id&&r.triple_id!==r.id)e.push('triple_id != id');
  if(typeof r.confidence!=='number'||r.confidence<0.7||r.confidence>1.0)e.push('bad confidence');
  if(r.domain&&CATS.indexOf(r.domain)<0)e.push('bad domain');
  return{ok:!e.length,errors:e};
}
