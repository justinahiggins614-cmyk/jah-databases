// gen-grandfather-clocks.js -- boundless generator for The Grandfather Clocks Database.
// Usage: node gen-grandfather-clocks.js --n 5
// Deterministic: a seeded LCG drives parameter variations of the 16 seed
// records. Self-regulating: throttled, duplicate-checked,
// hard-stops at 10^15 records or when the variation space is genuinely exhausted.
// Generated records carry "generated": true and src "generated" -- never mixed
// with assistant-built records.
"use strict";
const HARD_CAP = 1e15;
const TOPICS = ["Classic English Longcase Clock", "American Colonial Tall Case Clock", "Eight-Day Weight-Driven Movement", "Thirty-Hour Weight-Driven Movement", "Seconds Pendulum Fundamentals", "Moon-Phase Dial and Calendar Works", "Westminster Quarter Chime Movement", "Painted Dial, Spandrels and Chapter Ring", "Brass Dial with Silvered Chapter Ring", "Mahogany Chippendale-Style Case", "Oak Country Longcase", "Triple-Chime Musical Movement", "Astronomical and Equation-of-Time Complications", "Rack-and-Snail Striking Mechanism", "Restoration: Rebuilding a Longcase Movement", "Dating, Authenticating and Valuing a Longcase Clock"];
function parseN(argv) {
  const i = argv.indexOf("--n");
  if (i >= 0 && argv[i + 1]) {
    const n = parseInt(argv[i + 1], 10);
    if (!isNaN(n) && n >= 0) return Math.min(n, 100000);
  }
  return 5;
}
let seed = 20261026;
function rnd() {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}
const seen = new Set();
function makeRecord(k) {
  const topic = TOPICS[Math.floor(rnd() * TOPICS.length)];
  const variant = 1 + Math.floor(rnd() * 50);
  const key = topic + "#v" + variant;
  if (seen.has(key)) return null;
  seen.add(key);
  return {
    id: "JAH-GFC-GEN-" + String(k + 1).padStart(6, "0"),
    slug: "grandfather-clocks",
    title: "Generated " + topic + " parameter variation v" + variant,
    edition: "public",
    src: "generated",
    generated: true,
    built_by: "generator",
    record_kind: "grandfather clock record",
    note: "Deterministic parameter variation (" + key + ") over the 16 seed records. Labeled generated; not an assistant-built record."
  };
}
function main() {
  const n = parseN(process.argv.slice(2));
  if (n >= HARD_CAP) { console.error("hard cap reached"); process.exit(1); }
  const space = TOPICS.length * 50;
  let emitted = 0, attempts = 0;
  while (emitted < n && attempts < n * 20 && seen.size < space) {
    attempts++;
    const rec = makeRecord(emitted);
    if (rec) { console.log(JSON.stringify(rec)); emitted++; }
  }
  console.error("emitted " + emitted + " generated records for grandfather-clocks");
}
main();
