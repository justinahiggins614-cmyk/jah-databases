'use strict';
const TOPICS = ["Preparedness Baselines", "Cascading Risk Models", "Resource Requirement Estimates", "Recovery Strategy Catalogs", "Early Warning Integration", "Shelter Capacity Models", "Supply Prepositioning", "Communication Failure Plans", "Cross-Border Aid Protocols", "Resilience Investment Ranking", "Post-Disaster Assessment", "Vulnerable Population Registers", "Infrastructure Hardening Priorities", "Resilience Drills", "Recovery Progress Tracking", "Resilience Audit Reports"];
const HARD_CAP = 1000000000000000;
function parseN(argv) {
  const i = argv.indexOf("--n");
  if (i >= 0 && argv[i + 1]) {
    const n = parseInt(argv[i + 1], 10);
    if (!isNaN(n) && n >= 0) return Math.min(n, 100000);
  }
  return 5;
}
let seed = 20261025;
function rnd() {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}
const seen = new Set();
function makeRecord(k) {
  const topic = TOPICS[Math.floor(rnd() * TOPICS.length)];
  const variant = 1 + Math.floor(rnd() * 50);
  const key = topic + "#v" + variant;
  if (seen.has(key)) return null;
  seen.add(key);
  return {
    id: "JAH-GEN-" + String(k + 1).padStart(6, "0"),
    slug: "global-disaster-resilience",
    title: "Generated " + topic + " parameter variation v" + variant,
    edition: "public",
    src: "generated",
    generated: true,
    built_by: "generator",
    record_kind: "global disaster resilience record",
    feasibility_tier: "research-stage",
    note: "Deterministic parameter variation (" + key + ") over the 16 seed records. Labeled generated; not an assistant-built record."
  };
}
function main() {
  const n = parseN(process.argv.slice(2));
  if (n >= HARD_CAP) { console.error("hard cap reached"); process.exit(1); }
  const space = TOPICS.length * 50;
  let emitted = 0, attempts = 0;
  while (emitted < n && attempts < n * 20 && seen.size < space) {
    attempts++;
    const rec = makeRecord(emitted);
    if (rec) { console.log(JSON.stringify(rec)); emitted++; }
  }
  console.error("emitted " + emitted + " generated records for global-disaster-resilience");
}
main();
